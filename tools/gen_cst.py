#!/usr/bin/env python3
"""Write fpga/stage1.cst from the pin map the schematic was drawn from.

    python tools/gen_cst.py

hw/stage1/design.py's FPGA dict (FPGA pin -> net) is the only place pins are
assigned. This turns it into Gowin constraints, so the bitstream and the board
can't disagree about which pin carries what.
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "hw" / "stage1"))
import design  # noqa: E402


def port(net):
    for pre, name in (("F_A", "bus_a"), ("F_D", "bus_d")):
        if net.startswith(pre) and net[len(pre):].isdigit():
            return f"{name}[{net[len(pre):]}]"
    return {"F_RD_N": "bus_rd_n", "F_WR_N": "bus_wr_n", "F_SEL_N": "bus_sel_n"}[net]


def main():
    lines = ["// GENERATED by tools/gen_cst.py from hw/stage1/design.py -- edit the design, not this file.",
             "// Tang Nano 20K, GW2AR-LV18QN88C8/I7. Every header bank is 3.3 V (Sipeed datasheet).",
             'IO_LOC "clk_27m" 4;', 'IO_PORT "clk_27m" IO_TYPE=LVCMOS33 PULL_MODE=NONE;']
    for pin, net in sorted(design.FPGA.items(), key=lambda kv: kv[1]):
        p = port(net)
        lines.append(f'IO_LOC "{p}" {pin};')
        # Inputs are driven by the 74LVC245A outputs: no pull needed. The data pins
        # get a weak pull-down so they read 0, not noise, when nothing drives them.
        pull = "PULL_MODE=DOWN" if p.startswith("bus_d") else "PULL_MODE=NONE"
        drive = " DRIVE=8" if p.startswith("bus_d") else ""
        lines.append(f'IO_PORT "{p}" IO_TYPE=LVCMOS33 {pull}{drive};')
    out = ROOT / "fpga" / "stage1.cst"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT).as_posix()}: clock + {len(design.FPGA)} bus pins")


if __name__ == "__main__":
    main()
